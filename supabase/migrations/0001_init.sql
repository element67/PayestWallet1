-- NairaBridge schema for Supabase Postgres.
-- Conventions: timestamps are epoch milliseconds (BIGINT); flags stay 0/1 SMALLINT; every money or token amount is
-- NUMERIC, so sums are exact at any size (18-decimal tokens exceed 64-bit integers). The server connects as the
-- database owner; row level security is switched on for every table with no policies, so Supabase's public REST
-- API (anon and authenticated roles) can read and write nothing.

CREATE TABLE IF NOT EXISTS users (
  id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, name TEXT NOT NULL, password_hash TEXT,
  role TEXT NOT NULL DEFAULT 'user', kyc_tier INTEGER NOT NULL DEFAULT 1, status TEXT NOT NULL DEFAULT 'active',
  dev_preview SMALLINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL, last_login_at BIGINT,
  username TEXT, phone TEXT, display_currency TEXT NOT NULL DEFAULT 'USD'
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_username ON users(username) WHERE username IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_phone ON users(phone) WHERE phone IS NOT NULL;

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), expires_at BIGINT NOT NULL,
  created_at BIGINT NOT NULL, ip TEXT, device_fp TEXT, user_agent TEXT
